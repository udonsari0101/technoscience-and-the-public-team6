_BY_ID: dict[str, dict] = {p["id"]: p for p in PHILOSOPHERS}


def get_philosopher(philosopher_id: str | None) -> dict | None:
    return _BY_ID.get(philosopher_id or "")


def philosopher_ids() -> list[str]:
    return [p["id"] for p in PHILOSOPHERS]


def _lighten_for_dark_mode(hex_color: str) -> str:
    """Lighter variant of the accent so chips stay readable on dark surfaces."""
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    mix = lambda c: round(c + (255 - c) * 0.45)  # noqa: E731
    return f"#{mix(r):02X}{mix(g):02X}{mix(b):02X}"


def _darken(hex_color: str, amount: float = 0.15) -> str:
    """Darker accent for small chip text (>= 4.5:1 on the soft tint)."""
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    return "#%02X%02X%02X" % tuple(round(c * (1 - amount)) for c in (r, g, b))


def philosopher_css() -> str:
    """Per-philosopher colour tokens (served as a stylesheet; CSP forbids inline styles)."""
    rules = []
    for p in PHILOSOPHERS:
        rules.append(
            f".ph-{p['id']}{{--ph:{p['color']};--ph-soft:{p['color_soft']};"
            f"--ph-ink:{_darken(p['color'])};"
            f"--ph-on-dark:{_lighten_for_dark_mode(p['color'])};}}"
        )
    return "\n".join(rules) + "\n"
